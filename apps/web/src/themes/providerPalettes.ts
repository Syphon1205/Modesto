import { getStandardThemeColors, type ThemeColors, type ThemeDefinition } from "../themePalette";

function palette(base: ThemeColors, colors: Partial<ThemeColors>): ThemeColors {
  const merged = { ...base, ...colors };
  return {
    ...merged,
    toolbarControl: merged.secondary,
    toolbarControlForeground: merged.text,
    toolbarControlHover: merged.sidebarRowHover,
    placeholder: merged.textMuted,
    secondaryLabel: merged.textMuted,
    iconMuted: merged.textMuted,
    accentSurface: merged.secondary,
    accentSurfaceForeground: merged.text,
    messageAction: merged.accent,
    messageActionForeground: merged.accentForeground,
    messageActionHover: merged.sidebarRowHover,
    terminalBackground: merged.codeBackground,
    terminalForeground: merged.codeForeground,
    terminalCursor: merged.text,
    terminalSelection: merged.sidebarRowSelected,
    terminalScrollbar: merged.border,
    terminalScrollbarHover: merged.textMuted,
  };
}

