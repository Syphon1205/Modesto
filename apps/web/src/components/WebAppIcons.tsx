// multi-colour geometry is used verbatim - approximating those shapes by hand
// produces marks that read as the wrong logo. Marks with no colour identity of
// their own (Notion, GitHub, Sentry, Zendesk) inherit `currentColor` so they
// stay legible on light and dark chrome.

